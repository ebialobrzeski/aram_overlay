function rowToChampion(r: Row): Champion {
  const [id, alias, name, dmg, rng, cc, aoeCC, engage, poke, frontline, sustain, burst, dps, waveclear, airborne, aoeDmg, flags] = r;
  const traits: ChampionTraits = {
    cc, aoeCC, engage, poke, frontline, sustain, burst, dps, waveclear, airborne, aoeDmg, dmg, rng,
    hypercarry: flags.includes('H'), enchanter: flags.includes('E'), dive: flags.includes('D'),
    channelUlt: flags.includes('C'), allyUlt: flags.includes('G'),
  };
  return { id, alias, name, traits, curated: true };
}

