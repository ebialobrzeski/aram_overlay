export const CURATED_BY_ALIAS: Map<string, Champion> = new Map(CURATED.map(c => [c.alias.toLowerCase(), c]));

/** Fallback for champions missing from the curated table: derive rough traits from Data Dragon / LCU role tags. */
export function traitsFromTags(tags: string[], attackRange?: number): ChampionTraits {
  const t = new Set(tags.map(s => s.toLowerCase()));
  const ranged = attackRange !== undefined ? attackRange > 300 : t.has('marksman') || t.has('mage');
  const tr: ChampionTraits = {
    cc: 0, aoeCC: 0, engage: 0, poke: 0, frontline: 0, sustain: 0, burst: 0, dps: 0, waveclear: 1, airborne: 0, aoeDmg: 1,
    dmg: 'AD', rng: ranged ? 'ranged' : 'melee', hypercarry: false, enchanter: false, dive: false, channelUlt: false, allyUlt: false,
  };
  if (t.has('mage')) { tr.dmg = 'AP'; tr.poke = 2; tr.burst = 2; tr.cc = 1; tr.waveclear = 2; tr.aoeDmg = 2; }
  if (t.has('marksman')) { tr.dmg = 'AD'; tr.dps = 3; tr.poke = 1; tr.waveclear = 2; }
  if (t.has('tank')) { tr.frontline = 3; tr.cc = 2; tr.aoeCC = 1; tr.engage = 2; tr.dive = true; }
  if (t.has('fighter')) { tr.frontline = Math.max(tr.frontline, 2); tr.dps = Math.max(tr.dps, 2); tr.dive = true; }
  if (t.has('assassin')) { tr.burst = 3; tr.dive = true; }
  if (t.has('support')) { tr.sustain = 2; tr.cc = Math.max(tr.cc, 2); tr.enchanter = true; tr.dmg = 'AP'; }
  return tr;
}
